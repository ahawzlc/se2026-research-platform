/**
 * 好友模块的防骚扰参数（线③ 卡 E-3 评审意见 D3）。
 *
 * ## 为什么需要
 *
 * 好友申请有个天然的放大效应：**每申请一次就给对方发一条通知**，
 * 而「拒绝」是静默的（不给拒绝方发通知）。于是：
 *
 *   - 拿到 UID（主页上公开显示）→ 批量发申请 → 对方通知被刷屏；
 *   - 被拒后可以立刻再次申请 → 反复骚扰，且对方永远不知道是谁在试。
 *
 * UID 引入后「拿到 UID 就能发起搭话」这条路是通的，
 * 必须有机制拦住批量骚扰，否则公网部署就是可被利用的骚扰通道。
 *
 * ## 两道防线
 *
 * 1. **频率限流**（每人每天 N 次申请）——用 auth 模块的滑动窗口实现，
 *    挡住「短时间内批量发」的机器行为。
 * 2. **被拒冷却期**（被拒后 M 天内不能再向同一人申请）——挡住「专盯一个人」的定向骚扰。
 *
 * 冷却期内再申请返回 409 并说明原因与剩余时间。
 *
 * ## 参数取值
 *
 * 数字由牵头人定（见 docs/17-线③开发留痕.md 决策 6）：
 * 每天 20 次足够正常用户使用（加 10 个好友也就 10 次），
 * 又足以在一天内明显区分出机器批量行为。
 * 冷却期 3 天足以让被拒绝的人冷静下来，又不至于让误操作变成永久拉黑。
 */

/** 每人每天允许发起的好友申请次数 */
export const FRIEND_REQUEST_DAILY_LIMIT = 20;

/** 频率限流的窗口长度：一天（毫秒） */
export const FRIEND_REQUEST_WINDOW_MS = 24 * 60 * 60 * 1000;

/** 被拒后的冷却天数 */
export const FRIEND_REQUEST_COOLDOWN_DAYS = 3;

/** 一天的毫秒数（用于把剩余冷却时长换算成「剩余天数」） */
export const FRIEND_REQUEST_DAY_MS = 24 * 60 * 60 * 1000;

/** 被拒后的冷却时长（毫秒） */
export const FRIEND_REQUEST_COOLDOWN_MS =
  FRIEND_REQUEST_COOLDOWN_DAYS * FRIEND_REQUEST_DAY_MS;
